/**
 * Build the single-file CJS client bundle the DSH module loader expects.
 *
 * Source is split into small numbered sections for maintainability; this
 * script concatenates them inside the `window.__ModuleLoader__.load` factory.
 * No third-party build tool is required.
 */

import { readdir, readFile, writeFile, mkdir } from 'node:fs/promises'
import { spawnSync } from 'node:child_process'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)))
const sourceDir = join(root, 'src', 'client')
const output = join(root, 'lib', 'client.js')

const files = (await readdir(sourceDir))
  .filter((name) => name.endsWith('.js'))
  .sort()

const sections = []
for (const file of files) {
  const text = await readFile(join(sourceDir, file), 'utf8')
  sections.push(`\n/* ────────────────────────── ${file} ────────────────────────── */\n${text}`)
}

const header = `/**
 * dsh-ui-designer browser bundle.
 *
 * Generated by build.mjs from src/client/*.js — edit those files, then run
 * \`npm run build\`. The DSH module loader executes this file lazily and only
 * registers the factory; no UI code runs until the panel is materialized.
 */
window.__ModuleLoader__.load({
  id: 'dsh-ui-designer',
  factory(require) {
    const React = require('react')
    const h = React.createElement
`

const footer = `
  },
})
`

const bundle = header + sections.join('') + footer
await mkdir(dirname(output), { recursive: true })
await writeFile(output, bundle, 'utf8')

const check = spawnSync(process.execPath, ['--check', output], { encoding: 'utf8' })
if (check.status !== 0) {
  process.stderr.write(check.stderr || check.stdout || 'client bundle syntax check failed\n')
  process.exit(check.status || 1)
}

console.log(`built ${output} (${Buffer.byteLength(bundle, 'utf8')} bytes, ${files.length} sections)`)
